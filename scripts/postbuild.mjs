// Post-processing of the single-file build:
//  1. adds a strict Content-Security-Policy (no network access at all;
//     scripts allowed only by hash, so injected scripts can never run);
//  2. appends the licenses of every bundled third-party package;
//  3. writes dist/marklet.html and THIRD_PARTY_LICENSES.md.

import { readFileSync, writeFileSync, existsSync, readdirSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const input = join(root, "dist/index.html");
let html = readFileSync(input, "utf8");

// --- 1. Content Security Policy -------------------------------------------

html = html.replace(/<(script|link|style)([^>]*?)\s+crossorigin(?:="[^"]*")?/g, "<$1$2");
html = html.replace(/<style rel="stylesheet">/g, "<style>");

const hashes = [];
for (const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) {
  hashes.push(`'sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
}
if (!hashes.length) throw new Error("No inline script found in the build output.");

const csp = [
  "default-src 'none'",
  `script-src ${hashes.join(" ")}`,
  // CodeMirror injects its own <style> elements at runtime.
  "style-src 'unsafe-inline'",
  // Only embedded (data:) images; remote images would leak requests.
  "img-src data: blob:",
  "font-src data:",
  "connect-src 'none'",
  "media-src 'none'",
  "object-src 'none'",
  "frame-src 'none'",
  "worker-src 'none'",
  "manifest-src 'none'",
  "form-action 'none'",
  "base-uri 'none'",
].join("; ");

if (!html.includes("<!--CSP-->")) throw new Error("CSP placeholder missing from index.html.");
html = html.replace("<!--CSP-->", `<meta http-equiv="Content-Security-Policy" content="${csp}">`);

// --- 2. Third-party licenses ----------------------------------------------

function collect(name, seen = new Map()) {
  if (seen.has(name)) return seen;
  const dir = join(root, "node_modules", name);
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  const author = typeof meta.author === "string" ? meta.author : meta.author?.name;
  seen.set(name, {
    name,
    version: meta.version,
    license: meta.license,
    repository: typeof meta.repository === "string" ? meta.repository : meta.repository?.url,
    text: licenseFile
      ? readFileSync(join(dir, licenseFile), "utf8").trim()
      : `${meta.license} License${author ? `, Copyright (c) ${author}` : ""}. Full text: https://opensource.org/license/${String(meta.license).toLowerCase()}`,
  });
  for (const dep of Object.keys(meta.dependencies ?? {})) collect(dep, seen);
  return seen;
}
const deps = new Map();
for (const dep of Object.keys(pkg.dependencies ?? {})) collect(dep, deps);
const list = [...deps.values()].sort((a, b) => a.name.localeCompare(b.name));

const own = readFileSync(join(root, "LICENSE"), "utf8").trim();
const licenseText = [
  `Marklet ${pkg.version}`,
  "",
  own,
  "",
  "=".repeat(72),
  "Third-party software bundled in this file",
  "=".repeat(72),
  ...list.flatMap((d) => [
    "",
    `${d.name}@${d.version} (${d.license})`,
    d.repository ? `Source: ${d.repository}` : "",
    "",
    d.text,
    "",
    "-".repeat(72),
  ]),
].join("\n");

const comment = (s) => s.replace(/--+>/g, "-- >").replace(/<!--/g, "< !--");
html = html.replace(
  /<html([^>]*)>/,
  `<!--\n  Marklet ${pkg.version} - a portable, offline Markdown editor.\n  ${pkg.repository ?? ""}\n  Based on marqdown by Reiner Kempkes (https://github.com/marqdown/marqdown), MIT License.\n  Full license texts are at the end of this file.\n-->\n<html$1>`,
);
html = html.replace(/<\/html>\s*$/, `</html>\n<!--\n${comment(licenseText)}\n-->\n`);

writeFileSync(
  join(root, "THIRD_PARTY_LICENSES.md"),
  [
    "# Third-party licenses",
    "",
    "The built file `dist/marklet.html` bundles the following packages. This list is generated by `scripts/postbuild.mjs`.",
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
    ...list.map((d) => `| ${d.name} | ${d.version} | ${d.license} |`),
    "",
    ...list.flatMap((d) => [`## ${d.name}`, "", "```text", d.text, "```", ""]),
  ].join("\n"),
);

// --- 3. Output -------------------------------------------------------------

const output = join(root, "dist/marklet.html");
writeFileSync(output, html);
if (existsSync(input)) rmSync(input);
console.log(`✓ ${output} (${(Buffer.byteLength(html) / 1024).toFixed(0)} kB, ${list.length} bundled packages)`);
